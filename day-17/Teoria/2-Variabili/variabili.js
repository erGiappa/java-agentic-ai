// ==========================================
// 2. VARIABILI
// ==========================================

// VAR: vecchio metodo, oggi sconsigliato.
var nome = "John Michael";

// LET: variabile modificabile.
let eta = 29;
eta = 30;

// CONST: valore non riassegnabile.
const paese = "Italia";

console.log(nome);
console.log(eta);
console.log(paese);

// Esempio pratico: let
let punteggio = 10;
console.log("Punteggio iniziale:", punteggio);

punteggio = 20;
console.log("Nuovo punteggio:", punteggio);

// Esempio di CONST
const PI = 3.14159;
console.log("Valore di PI:", PI);

// NOTA:
// const non permette di riassegnare una variabile.
// Ma se contiene un oggetto o un array,
// possiamo modificarne il contenuto.

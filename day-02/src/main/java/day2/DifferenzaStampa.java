package day2;

public class DifferenzaStampa {
    public static void main(String[] args) {
        // print() stampa il messaggio senza andare a capo.
        System.out.print("Primo messaggio con print. ");
        System.out.print("Secondo messaggio con print. ");

        // println() senza argomenti produce un'interruzione di riga.
        System.out.println();

        // println() stampa il messaggio e successivamente va a capo.
        System.out.println("Primo messaggio con println");
        System.out.println("Secondo messaggio con println");
    }
}

package com.ergiappa;


public class Dichiarazioni {
    public static void main(String[] args) {

        // Dichiarazione di più variabili sulla stessa riga:
        int a = 1, b = 2, c = 3;

        System.out.println("Dichiarazioni multiple:");
        System.out.println("a = " + a);
        System.out.println("b = " + b);
        System.out.println("c = " + c);

        // Dichiarazione delle variabili su righe separate:
        int x = 1;
        int y = 2;
        int z = 3;

        // Le dichiarazioni singole sono generalmente più leggibili:
        // ogni variabile ha una propria riga, quindi è più facile
        // individuare il nome e il valore assegnato.
        // Inoltre, è più semplice modificare o aggiungere variabili.
        System.out.println("Dichiarazioni singole:");
        System.out.println("x = " + x);
        System.out.println("y = " + y);
        System.out.println("z = " + z);
    }
}


package com.ergiappa;

public class Conversioni {
    public static void main(String[] args) {
        int a = 5;
        double b = a;
        int c = (int) b;

        System.out.println("Il valore di a (int) è: " + a);
        System.out.println("Il valore di b (double) è: " + b);
        System.out.println("Il valore di c (int) è: " + c);

    }
}

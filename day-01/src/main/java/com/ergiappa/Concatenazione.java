package com.ergiappa;

public class Concatenazione {
    public static void main(String[] args) {
        String prima = "Ciao ";
        String seconda = "Mondo";

        // L'operatore + concatena le due stringhe.
        // La concatenazione produce una nuova stringa
        // con il contenuto "Ciao Mondo", senza modificare
        // le stringhe originali.
        String risultato = prima + seconda;

        System.out.println(risultato);
    }
}

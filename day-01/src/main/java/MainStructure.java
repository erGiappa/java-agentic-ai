/**
 * Primo esempio di struttura di un programma Java.
 * Una classe pubblica di primo livello deve avere
 * lo stesso nome del file sorgente.
 * In questo caso:
 * Classe: MainStructure
 * File: MainStructure.java
 */


/*
 * Metodo main:
 * è il punto di ingresso convenzionale del programma.
 *
 * public  -> accessibile dall'esterno.
 * static  -> appartiene alla classe, non a un'istanza.
 * void    -> non restituisce alcun valore.
 * String[] args -> array contenente gli argomenti
 *                  eventualmente passati all'avvio.
 */


public class MainStructure {

    public static void main(String[] args){
        System.out.println("Hello World!");
        System.out.println("Questo è un altro 'Ciao mondo!'");
    }
}

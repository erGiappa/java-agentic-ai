package day3;

public class WhileUnoDieci {
    public static void main(String[] args) {

        // La stampa parte da 10 e procede verso il valore 1.
        int num = 10;

        // Il contatore viene decrementato ad ogni iterazione.
        while (num >= 1) {
            System.out.println(num);
            num--;
        }
    }
}
